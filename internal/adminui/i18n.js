const storageKey = "agent-post.locale";
function resolveLocale(value) {
  if (typeof value !== "string") return null;
  const pieces = value.replaceAll("_", "-").toLowerCase().split("-");
  if (pieces[0] === "zh") {
    if (pieces.includes("hant")) return "zh-Hant";
    if (pieces.includes("hans")) return "zh-Hans";
    return pieces.some(part => ["tw", "hk", "mo"].includes(part)) ? "zh-Hant" : "zh-Hans";
  }
  return ["en", "fr", "it", "es", "ru"].includes(pieces[0]) ? pieces[0] : null;
}
function initialLocale() {
  try { const saved = resolveLocale(localStorage.getItem(storageKey)); if (saved) return saved; } catch {}
  for (const preference of navigator.languages || [navigator.language]) {
    const match = resolveLocale(preference); if (match) return match;
  }
  return "en";
}
let locale = initialLocale();
function formatNumber(value) { return new Intl.NumberFormat(locale).format(value); }
function formatDate(value) {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? "—" : new Intl.DateTimeFormat(locale, {dateStyle: "medium", timeStyle: "medium"}).format(date);
}
function t(key, params = {}) {
  const template = catalogs[locale][key] ?? catalogs.en[key] ?? catalogs[locale]["error.generic"];
  return template.replace(/\{([a-z_]+)\}/gi, (token, name) => {
    const value = params[name];
    return value === undefined ? token : typeof value === "number" ? formatNumber(value) : String(value);
  });
}
function apply(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(node => {
    node.textContent = t(node.dataset.i18n, node._i18nParams || {});
  });
  for (const [attribute, dataName] of [["placeholder", "i18nPlaceholder"], ["aria-label", "i18nAriaLabel"], ["title", "i18nTitle"]]) {
    root.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)}]`).forEach(node => node.setAttribute(attribute, t(node.dataset[dataName])));
  }
  root.querySelectorAll("[data-i18n-language]").forEach(select => { select.value = locale; });
  document.documentElement.lang = locale;
  document.title = `Agent Post · ${t("Administration")}`;
}
function setLocale(value) {
  const next = resolveLocale(value) || "en";
  locale = next;
  try { localStorage.setItem(storageKey, next); } catch {}
  apply();
  window.dispatchEvent(new CustomEvent("agentpost:languagechange", {detail: {locale}}));
}
